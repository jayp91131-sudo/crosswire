"""
Data models for Crosswire DAST Engine findings and invariant validations.
"""

from enum import Enum
from typing import Optional, Dict, Any, List
from pydantic import BaseModel, Field


class InvariantType(str, Enum):
    BOOKING_INTENT_UNIQUENESS = "BOOKING_INTENT_UNIQUENESS"
    WEBHOOK_IDEMPOTENCY = "WEBHOOK_IDEMPOTENCY"
    WALLET_BALANCE_DERIVATION = "WALLET_BALANCE_DERIVATION"
    VOUCHER_ENTITLEMENT = "VOUCHER_ENTITLEMENT"
    REFUND_BOUNDEDNESS = "REFUND_BOUNDEDNESS"
    SAFE_AMBIGUOUS_FALLBACK = "SAFE_AMBIGUOUS_FALLBACK"
    FINANCIAL_CONSISTENCY = "FINANCIAL_CONSISTENCY"
    WALLET_OVERDRAFT_PROTECTION = "WALLET_OVERDRAFT_PROTECTION"
    HOTEL_INVENTORY_CAPACITY = "HOTEL_INVENTORY_CAPACITY"
    IDEMPOTENCY_PAYLOAD_CONGRUENCE = "IDEMPOTENCY_PAYLOAD_CONGRUENCE"
    SAGA_COMPENSATION_CONSISTENCY = "SAGA_COMPENSATION_CONSISTENCY"
    CROSS_AGENCY_WALLET_ISOLATION = "CROSS_AGENCY_WALLET_ISOLATION"
    WALLET_HOLD_EXCLUSIVITY = "WALLET_HOLD_EXCLUSIVITY"
    WALLET_REFUND_CONSERVATION = "WALLET_REFUND_CONSERVATION"
    INVENTORY_ALLOCATION_CONSERVATION = "INVENTORY_ALLOCATION_CONSERVATION"
    CANCELLATION_INVENTORY_CONSERVATION = "CANCELLATION_INVENTORY_CONSERVATION"
    AMBIGUOUS_TIMEOUT_HOLD_PRESERVATION = "AMBIGUOUS_TIMEOUT_HOLD_PRESERVATION"


class Severity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INFO = "INFO"


class InvariantCheckResult(BaseModel):
    invariant: InvariantType
    passed: bool
    intent_id: str
    expected: Any
    actual: Any
    cwe: Optional[str] = None
    severity: Optional[Severity] = None
    title: str
    description: str
    evidence: Dict[str, Any] = Field(default_factory=dict)
    remediation: Optional[str] = None
